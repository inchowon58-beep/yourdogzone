export function resolveCatMbtiType(
  answers: Array<"E" | "I" | "S" | "N" | "T" | "F" | "J" | "P">
): MbtiType {
  const count: Record<string, number> = {
    E: 0,
    I: 0,
    S: 0,
    N: 0,
    T: 0,
    F: 0,
    J: 0,
    P: 0,
  };
  for (const a of answers) count[a] += 1;
  const code =
    (count.E >= count.I ? "E" : "I") +
    (count.S >= count.N ? "S" : "N") +
    (count.T >= count.F ? "T" : "F") +
    (count.J >= count.P ? "J" : "P");
  const meta = CAT_TYPES[code] ?? CAT_TYPES.ISFJ;
  return {
    code,
    ...meta,
    summary: meta.summary.replace(/Reinforcement/g, "강화"),
  };
}
